const packs: Record<Locale, Dict> = { en };

const i18nStore = createStore<{ locale: Locale }>({ locale: 'en' });

/**
 * Translate. Missing keys return the key itself and warn in development, so an
 * untranslated string is visible in review rather than silently blank.
 */
export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = packs[i18nStore.get().locale] ?? en;
  let s = dict[key];
  if (s === undefined) {
    if (import.meta.env.DEV) console.warn(`[i18n] missing key: ${key}`);
    return key;
  }
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function setLocale(locale: Locale): void {
  i18nStore.set({ locale });
  document.documentElement.lang = locale;
  // When an RTL pack is added this is where dir flips — the only place.
  document.documentElement.dir = 'ltr';
}

export const useLocale = () => useStore(i18nStore, (s) => s.locale);
